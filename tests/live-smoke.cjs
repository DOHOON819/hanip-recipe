const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.RECIPE_BOOK_PLAYWRIGHT || 'playwright');
(async () => {
  const url = process.argv[2];
  if (!url || !/^https?:/.test(url)) throw new Error('Pass the site URL to test.');
  const out = path.resolve(process.env.RECIPE_BOOK_TEST_OUTPUT || 'test-results');
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless:true, ...(process.env.RECIPE_BOOK_BROWSER ? {executablePath:process.env.RECIPE_BOOK_BROWSER} : {}) });
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1050}});
    const errors = [];
    const failedAssets = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() >= 400 && /\.(js|css|jpg|svg)(\?|$)/.test(response.url())) failedAssets.push(response.url() + ' ' + response.status()); });
    await page.goto(url, {waitUntil:'networkidle'});
    await page.waitForFunction(() => document.querySelector('#recipeGrid')?.getAttribute('aria-busy') === 'false');
    assert.equal(await page.title(), 'Recipe Story — Good food. Worth sharing.');
    assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), 'https://dohoon819.github.io/hanip-recipe/');
    assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /index,follow/);
    const verification = await page.evaluate(() => fetch('google6bf2038a52595488.html').then(response => response.text()));
    assert.equal(verification.trim(), 'google-site-verification: google6bf2038a52595488.html');
    const sitemap = await page.evaluate(() => fetch('sitemap.xml').then(response => response.text()));
    assert.match(sitemap, /https:\/\/dohoon819\.github\.io\/hanip-recipe\//);
    assert.equal(await page.locator('#languageSelect').count(), 1);
    assert.equal(await page.locator('#languageSelect option[value="en-AU"]').count(),1);
    assert.equal(await page.locator('#recipeCategory option[value="아랍식"]').count(),1);
    assert.equal(await page.locator('#recipeCategory option[value="호주식"]').count(),1);
    assert.equal(await page.locator('#recipeDescription').getAttribute('required'),'');
    assert.equal(await page.locator('#recipeCuisine').getAttribute('required'),'');
    assert.ok(await page.locator('[data-open-shorts]').count()>=3);
    await page.locator('#languageSelect').selectOption('ko');
    assert.equal(await page.locator('html').getAttribute('lang'), 'ko');
    assert.match(await page.locator('#heroTitle').innerText(), /맛있는 레시피/);
    await page.locator('#languageSelect').selectOption('ja');
    assert.equal(await page.locator('html').getAttribute('lang'), 'ja');
    assert.match(await page.locator('#heroTitle').innerText(), /おいしい料理/);
    const feedAvailable = !(await page.locator('#retryButton').isVisible());
    if (!process.env.RECIPE_BOOK_ALLOW_FEED_FAILURE) assert.equal(feedAvailable, true, 'Production feed is unavailable');
    assert.equal(await page.locator('.hero-visual img').evaluate(image => image.complete && image.naturalWidth > 0), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const host = new URL(url).hostname;
    await page.screenshot({path:path.join(out, host+'-desktop.png'),fullPage:true});
    const count = await page.locator('.recipe-card').count();
    await page.locator('#languageSelect').selectOption('ar');
    assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
    await page.locator('[data-open-shorts]').first().click();
    assert.equal(await page.locator('#shortsDialog').isVisible(),true);
    assert.equal(await page.locator('#shortsViewport').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
    await page.locator('[data-close-shorts]').click();
    await page.locator('#languageSelect').selectOption('ko');
    await page.locator('[data-media-filter="video"]').click();
    await page.locator('[data-media-filter="image"]').click();
    await page.locator('[data-media-filter="all"]').click();
    await page.locator('#openComposer').click();
    assert.equal(await page.locator('#composerDialog').isVisible(),true,'editor opens without creating a guest account');
    await page.locator('[data-close-dialog="composerDialog"]').click();
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(() => scrollTo(0,0));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path:path.join(out, host+'-mobile.png'),fullPage:true});
    assert.deepEqual(errors, []);
    assert.deepEqual(failedAssets, []);
    console.log(JSON.stringify({url,title:await page.title(),feedAvailable,recipes:count,mobileOverflow:false,pageErrors:errors,failedAssets}));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
