const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const policy = read('privacy.html');
const index = read('index.html');
assert.match(policy, /<title>Privacy Policy · 개인정보처리방침 \| Recipe Story<\/title>/);
assert.match(policy, /https:\/\/dohoon819\.github\.io\/hanip-recipe\/privacy\.html/);
assert.match(policy, /io\.github\.dohoon819\.recipestory/);
assert.match(policy, /mailto:dohoon754@gmail\.com/);
assert.match(policy, /DOHOON819/);
assert.match(policy, /id="en" lang="en"/);
assert.match(policy, /id="ko" lang="ko"/);
assert.match(policy, /id="contact-en"/);
assert.match(policy, /id="contact-ko"/);
assert.doesNotMatch(policy, /<script\b|<iframe\b|contenteditable|sb_secret_|service_role|TODO|\[your /i);
assert.doesNotMatch(policy, /<img[^>]+src="https?:|<link[^>]+rel="(?:stylesheet|preconnect|preload)"[^>]+href="https?:/i, 'Policy must not load third-party resources');
for (const host of ['nos.lol', 'relay.primal.net', 'relay.nostr.band', 'nostrage.com/api/v2/media', 'cdn.nostrcheck.me']) assert.ok(policy.includes(host), host);
for (const text of ['localStorage', '100', 'metadata', 'IP address', 'retention', 'deletion', 'public key', 'private key', 'HTTPS', 'WSS', 'Supabase', 'GitHub', 'jsDelivr', 'Google Fonts']) assert.ok(policy.includes(text), text);
assert.ok((index.match(/data-privacy-link/g) || []).length >= 2, 'Footer and profile need links');
assert.ok(index.includes('data-privacy-contact'));
assert.match(read('sitemap.xml'), /<loc>https:\/\/dohoon819\.github\.io\/hanip-recipe\/privacy\.html<\/loc>/);
assert.equal(read('google6bf2038a52595488.html').trim(), 'google-site-verification: google6bf2038a52595488.html');
// All consumers must share one i18n module instance after the cache-busting change.
const appImport = read('app.js').match(/from '(\.\/i18n\.js[^']*)'/)[1];
const socialImport = read('social.js').match(/from '(\.\/i18n\.js[^']*)'/)[1];
assert.equal(appImport, socialImport);
console.log('PASS: bilingual static privacy page, contact, provider disclosures, app links, sitemap, shared i18n version and verification file');
